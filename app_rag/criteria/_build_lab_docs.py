    path = CRIT / "LAB_cards.yaml"
    # PyYAML dump
    data = []
    for c in CARDS:
        row = {
            "id": c["id"],
            "title": c["title"],
            "match_keywords": c["match_keywords"],
            "safe": c["safe"],
            "violation": c["violation"],
            "check_if": c["check_if"],
            "needs_facts": c["needs_facts"],
            "basis": c["basis"],
        }
        if c.get("missing_basis"):
            row["missing_basis"] = c["missing_basis"]
        data.append(row)
    path.write_text(
        yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8",
    )
    return data


