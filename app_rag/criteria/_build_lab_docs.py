def card_body_len(card: dict) -> int:
    parts = []
    for k in ("title", "safe", "violation", "check_if", "match_keywords", "needs_facts", "basis", "missing_basis"):
        v = card.get(k)
        if isinstance(v, list):
            parts.extend(str(x) for x in v)
        elif v:
            parts.append(str(v))
    return len("".join(parts))


